// Writes src/data/queries.ts: one server function per query of the data
// seam's contract (src/data/queries.contract.ts), spelled out because
// Start's compiler only finds server functions declared statically. Pages
// call the exports with the query's own arguments; the handler runs the
// query on the server through the live adapters (src/data/backend.ts).
//
//   bun scripts/gen-queries.ts           write
//   bun scripts/gen-queries.ts --check   fail when the file is stale (tests)
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { queryNames } from '../src/data/backend'
import { isRead } from '../src/data/readOnly'

const root = join(import.meta.dirname, '..')
const contractSource = readFileSync(join(root, 'src/data/queries.contract.ts'), 'utf8')
const types = [...contractSource.matchAll(/^export (?:type|interface) (\w+)/gm)].map((m) => m[1]).filter((name) => name !== 'Queries').sort()

export function renderQueries(): string {
  const names = queryNames().sort()
  const lines = [
    '// Generated by scripts/gen-queries.ts from src/data/queries.contract.ts: do not edit.',
    '//',
    '// The data seam every page imports. Each query is a server function: the',
    "// page calls it with the query's own arguments, the handler runs it on the",
    '// server through the live adapters (src/data/backend.ts, src/data/api.ts).',
    '// The backend and its token never reach the browser.',
    "import { createServerFn } from '@tanstack/react-start'",
    "import type { Queries } from './queries.contract'",
    "import { announced } from './serverFn'",
    "import type { Json } from './serverFn'",
    '',
    "export { alertKeyOf, generatePassword, inRange, redact } from './shared'",
    `export type { ${types.join(', ')} } from './queries.contract'`,
    '',
  ]
  for (const name of names) {
    lines.push(
      `const ${name}Fn = createServerFn({ method: '${isRead(name) ? 'GET' : 'POST'}' })`,
      '  .validator((args: unknown[]) => args)',
      `  .handler(async ({ data }) => (await (await import('./backend')).runForRequest('${name}', data)) as Json)`,
      `export const ${name} = announced('${name}', ${name}Fn) as Queries['${name}']`,
      '',
    )
  }
  return lines.join('\n')
}

if (import.meta.main) {
  const path = join(root, 'src/data/queries.ts')
  const next = renderQueries()
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== next) {
      console.error('src/data/queries.ts is stale: run bun scripts/gen-queries.ts')
      process.exit(1)
    }
  } else {
    writeFileSync(path, next)
    console.log(`src/data/queries.ts: ${queryNames().length} server functions`)
  }
}
